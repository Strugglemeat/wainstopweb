const shelf = document.getElementById("shelf");
const screen = document.getElementById("screen");

function rows() {
    const size = window.matchMedia("(max-width: 600px)").matches ? 32 : 40;
    const across = Math.max(1, Math.floor((shelf.clientWidth + 3) / (size + 3)) - 4);
    const spare = (across - tapes.length % across) % across;
    shelf.style.gridTemplateColumns = "repeat(" + across + ", " + size + "px)";
    shelf.firstElementChild.style.gridColumnStart = spare + 1;
    document.querySelector(".player").style.marginLeft = (shelf.clientWidth - across * size - (across - 1) * 3) / 2 + "px";
}

for (let n = tapes.length - 1; n > 0; n--) {
    const pick = Math.floor(Math.random() * (n + 1));
    [tapes[n], tapes[pick]] = [tapes[pick], tapes[n]];
}

function play(tape, start) {
    screen.src = "https://www.youtube.com/embed/" + tape[0] + (start ? "?autoplay=1" : "");
    screen.title = tape[1];
}

for (const tape of tapes) {
    const link = document.createElement("a");
    const picture = document.createElement("img");
    link.href = "https://www.youtube.com/watch?v=" + tape[0];
    link.target = "_blank";
    link.rel = "noopener";
    link.title = tape[1];
    picture.src = "https://i.ytimg.com/vi/" + tape[0] + "/mqdefault.jpg";
    picture.alt = tape[1];
    picture.width = 320;
    picture.height = 180;
    link.append(picture);
    link.addEventListener("click", function (event) {
        if (event.ctrlKey || event.metaKey || event.shiftKey || event.altKey) return;
        event.preventDefault();
        play(tape, true);
    });
    shelf.append(link);
}

play(tapes[0], false);
rows();
window.addEventListener("resize", rows);
